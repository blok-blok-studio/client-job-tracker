/**
 * Sequence definitions A–I: triggers, steps, default timing offsets, and
 * cancel conditions. Offsets are editable in the portal (SequenceStepConfig);
 * everything else here is the fixed shape of each sequence.
 *
 * Step kinds:
 *  EMAIL — auto-sent when due (subject to sequence enabled + master switch + dry run)
 *  DRAFT — pre-filled draft created as an internal task, a human sends it
 *  TASK  — internal task only, never emails anyone
 */

const H = 60;
const D = 24 * H;

export type CancelConditionKey =
  | "kickoff_booked"
  | "assets_received"
  | "care_decided";

export const CANCEL_CONDITIONS: Record<
  CancelConditionKey,
  { description: string }
> = {
  kickoff_booked: {
    description: "Cancelled when a kickoff call is booked (kickoff booked date set)",
  },
  assets_received: {
    description: "Cancelled when the client's content arrives (assets received date set)",
  },
  care_decided: {
    description:
      "Cancelled when care status changes from free (client converts or declines). If the client books the call from the earlier email, skip this step manually on their timeline.",
  },
};

export interface StepSource {
  key: string;
  label: string;
  kind: "EMAIL" | "DRAFT" | "TASK";
  templateKey?: string;
  offsetMinutes: number;
  offsetBounds: [number, number]; // sane editing bounds, minutes
  cancelCondition?: CancelConditionKey;
  taskTitle?: string; // {{token}} rendered
  taskDescription?: string;
  checklist?: string[];
  manualTrigger?: boolean; // not materialized from the anchor — the engine creates it on a specific event (e.g. care declined)
}

export interface SequenceSource {
  key: string;
  name: string;
  trigger: string; // human description shown in the editor
  anchorDescription: string;
  audience: "client" | "contractor" | "global";
  recurring?: boolean; // steps generated by the cron scanner, not materialized from a one-time trigger
  steps: StepSource[];
}


export const SEQUENCE_SOURCE_BY_KEY: Record<string, SequenceSource> = Object.fromEntries(
  SEQUENCE_SOURCES.map((s) => [s.key, s])
);

export function stepSource(sequenceKey: string, stepKey: string): StepSource | null {
  return SEQUENCE_SOURCE_BY_KEY[sequenceKey]?.steps.find((s) => s.key === stepKey) || null;
}
